class SwiftLaTeXEngine {
  private engineStatus: EngineStatus = EngineStatus.Init;
  private realEngine: any = null;

  async loadEngine(): Promise<void> {
    if (typeof window.XeTeXEngine === 'undefined') {
      console.error('XeTeXEngine not loaded. Waiting for script...');
      // Simple wait loop
      for (let i = 0; i < 10; i++) {
        if (typeof window.XeTeXEngine !== 'undefined') break;
        await new Promise(r => setTimeout(r, 500));
      }
      if (typeof window.XeTeXEngine === 'undefined') {
        throw new Error('XeTeXEngine library not found. Please ensure /swiftlatex/XeTeXEngine.js is loaded.');
      }
    }

    try {
      this.realEngine = new window.XeTeXEngine();
      const texliveEndpoint = `${window.location.origin}/swiftlatex/texlive/`;
      this.realEngine.setTexliveEndpoint(texliveEndpoint);
      await this.realEngine.loadEngine();
      // Try to generate the format file, but don't fail if remote fetch is blocked
      try {
        const fmtBuffer = await Promise.race([
          this.realEngine.compileFormat(),
          new Promise((_, reject) => setTimeout(() => reject(new Error('Format compilation timeout')), 3000))
        ]);
        if (fmtBuffer) {
          // Write the format file with the correct name
          this.writeMemFSFile('swiftlatexxetex.fmt', new Uint8Array(fmtBuffer));
        }
      } catch (fmtError) {
        console.warn('Format compilation skipped (may be normal in dev):', fmtError);
        // Continue without format file - engine will attempt to compile anyway
      }
      this.engineStatus = EngineStatus.Ready;
      console.log('✅ Local SwiftLaTeX Engine loaded successfully');
    } catch (e) {
      console.error('Failed to load SwiftLaTeX engine:', e);
      this.engineStatus = EngineStatus.Error;
      throw e;
    }
  }

  isReady(): boolean {
    return this.engineStatus === EngineStatus.Ready && this.realEngine && this.realEngine.isReady();
  }

  isEngineReady(): boolean {
    return this.isReady();
  }

  writeMemFSFile(filename: string, content: string): void {
    if (this.realEngine) {
      this.realEngine.writeMemFSFile(filename, content);
    }
  }

  setEngineMainFile(filename: string): void {
    if (this.realEngine) {
      this.realEngine.setEngineMainFile(filename);
    }
  }

  flushCache(): void {
    if (this.realEngine) {
      this.realEngine.flushCache();
    }
  }

  async compile(files: LaTeXFile[], mainFile: string = 'main.tex'): Promise<CompileResult> {
    // Initialize if needed
    if (!this.isReady()) {
      await this.loadEngine();
    }

    // Flush cache to clear any previous files
    this.flushCache();

    // Validate main file content
    const mainFileData = files.find(f => f.name === mainFile || f.path === `/${mainFile}`);
    if (mainFileData && !mainFileData.content.trim().startsWith('\\documentclass')) {
      return {
        success: false,
        log: `Invalid LaTeX content: Main file must start with \\documentclass. Found: ${mainFileData.content.substring(0, 50)}...`,
        errors: ['Main file does not contain valid LaTeX document structure'],
        warnings: []
      };
    }

    // Write all files to engine
    for (const file of files) {
      this.writeMemFSFile(file.name, file.content);
    }

    // Set main file
    this.setEngineMainFile(mainFile);

    console.log('🚀 Starting Local SwiftLaTeX Compilation...');

    try {
      const result = await this.realEngine.compileLaTeX();

      // Map engine result to our CompileResult type
      const success = result.status === 0 || (result.pdf && result.pdf.length > 0);

      let pdfUrl = undefined;
      // result.pdf is a Uint8Array
      if (success && result.pdf) {
        const blob = new Blob([result.pdf], { type: 'application/pdf' });
        pdfUrl = URL.createObjectURL(blob);
      }

      return {
        success,
        pdfUrl,
        pdfData: result.pdf,
        log: result.log,
        errors: success ? [] : this.extractErrors(result.log || ''),
        warnings: this.extractWarnings(result.log || '')
      };

    } catch (e) {
      console.error('Local compilation failed:', e);
      // Fallback to preview if compilation fails hard
      return this.generatePreviewPdf(files, mainFile, e instanceof Error ? e.message : 'Unknown compilation error');
    }
  }

  // Legacy/Fallback methods kept empty
  private async tryDirectLatexAPIs(content: string, filename: string): Promise<CompileResult> {
    return { success: false, log: 'Direct API disabled', errors: [], warnings: [] };
  }

  private async tryGeminiCodeExecution(content: string, filename: string): Promise<CompileResult> {
    return { success: false, log: 'Code Execution disabled', errors: [], warnings: [] };
  }

  private generatePreviewPdf(files: LaTeXFile[], mainFile: string, errorMsg: string): CompileResult {
    // Create a beautiful HTML preview for when compilation fails
    const mainFileData = files.find(f => f.path === mainFile || f.path === `/${mainFile}`);

    // Extract title and content from LaTeX
    const content = mainFileData?.content || '';
    const titleMatch = content.match(/\\title\{([^}]+)\}/);
    const authorMatch = content.match(/\\author\{([^}]+)\}/);
    const title = titleMatch ? titleMatch[1].replace(/\\textbf\{([^}]+)\}/, '$1').replace(/\\\\/g, ' ') : 'LaTeX Document';
    const author = authorMatch ? authorMatch[1].replace(/\\\\/g, ', ') : '';

    // Extract sections for preview
    const sections: { title: string, content: string }[] = [];
    const sectionRegex = /\\section\{([^}]+)\}([^]*?)(?=\\section\{|\\end\{document\}|$)/g;
    let sectionMatch;
    while ((sectionMatch = sectionRegex.exec(content)) !== null) {
      sections.push({
        title: sectionMatch[1],
        content: sectionMatch[2].substring(0, 500).trim()
      });
    }

    // Escape HTML in content
    const escapeHtml = (text: string) => {
      return text
        .replace(/&/g, '&amp;')
        .replace(/</g, '&lt;')
        .replace(/>/g, '&gt;')
        .replace(/"/g, '&quot;')
        .replace(/'/g, '&#039;');
    };

    return {
      success: false,
      log: `Local Compilation Failed: ${errorMsg}\n\nFalling back to preview mode.`,
      errors: [errorMsg],
      warnings: ['Using HTML preview due to compilation error']
    };
  }

  private extractErrors(log: string): string[] {
    const errors: string[] = [];
    const errorPatterns = [
      /^! (.+)$/gm,
      /^l\.(\d+) (.+)$/gm,
      /Error: (.+)/gi
    ];

    for (const pattern of errorPatterns) {
      let match;
      while ((match = pattern.exec(log)) !== null) {
        errors.push(match[0]);
      }
    }
    return [...new Set(errors)];
  }

  private extractWarnings(log: string): string[] {
    const warnings: string[] = [];
    const warningPatterns = [
      /Warning: (.+)/gi,
      /Overfull \\hbox (.+)/g,
      /Underfull \\hbox (.+)/g
    ];

    for (const pattern of warningPatterns) {
      let match;
      while ((match = pattern.exec(log)) !== null) {
        warnings.push(match[0]);
      }
    }
    return [...new Set(warnings)];
  }

  closeEngine(): void {
    if (this.realEngine) {
      try {
        if (typeof this.realEngine.closeWorker === 'function') {
          this.realEngine.closeWorker();
        }
      } catch (e) {
        console.warn('Failed to close worker', e);
      }
    }
    this.engineStatus = EngineStatus.Init;
    this.realEngine = null;
  }
}

class TodoManager {
  private todos: LaTeXTodoItem[] = [];

  // write_todos - Update the entire todo list
  writeTodos(todos: LaTeXTodoItem[]): void {
    this.todos = todos;
  }

  // Add a new todo
  addTodo(title: string, description?: string, priority: 'high' | 'medium' | 'low' = 'medium'): LaTeXTodoItem {
    const todo: LaTeXTodoItem = {
      id: `todo-${Date.now()}-${Math.random().toString(36).substr(2, 9)}`,
      title,
      description,
      status: 'pending',
      priority
    };
    this.todos.push(todo);
    return todo;
  }

  // Update todo status
  updateTodoStatus(id: string, status: 'pending' | 'in-progress' | 'completed'): boolean {
    const todo = this.todos.find(t => t.id === id);
    if (todo) {
      todo.status = status;
      return true;
    }
    return false;
  }

  // Get all todos
  getTodos(): LaTeXTodoItem[] {
    return [...this.todos];
  }

  // Get todos by status
  getTodosByStatus(status: 'pending' | 'in-progress' | 'completed'): LaTeXTodoItem[] {
    return this.todos.filter(t => t.status === status);
  }

  // Clear all todos
  clear(): void {
    this.todos = [];
  }

  // Generate a summary of todos
  getSummary(): string {
    const pending = this.todos.filter(t => t.status === 'pending').length;
    const inProgress = this.todos.filter(t => t.status === 'in-progress').length;
    const completed = this.todos.filter(t => t.status === 'completed').length;
    return `Tasks: ${completed}/${this.todos.length} completed, ${inProgress} in progress, ${pending} pending`;
  }
}

