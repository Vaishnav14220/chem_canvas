interface ToolDefinition {
  name: string;
  description: string;
  execute: (params: any, context: AgentContext) => Promise<string>;
}

interface AgentContext {
  fileSystem: LaTeXFileSystem;
  todoManager: TodoManager;
  engine: SwiftLaTeXEngine;
  genAI: GoogleGenAI;
}

